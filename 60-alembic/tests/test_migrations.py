# The migrations are code: test them like code - on the same PostgreSQL as production
import os
import subprocess
import sys
import time

import psycopg
import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from alembic.util import CommandError

from app.db import head_revision
from tests.conftest import ROOT, URL, drop_everything

VIDEO_59 = """CREATE TABLE courses (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    title text NOT NULL CHECK (length(title) BETWEEN 3 AND 80),
    created_at timestamptz NOT NULL DEFAULT now(),
    description text)"""


def version() -> str | None:
    with psycopg.connect(URL) as conn:
        if conn.execute("SELECT to_regclass('alembic_version')").fetchone()[0] is None:
            return None
        row = conn.execute("SELECT version_num FROM alembic_version").fetchone()
        return row[0] if row else None


def alembic(*args: str, **env: str) -> subprocess.Popen:
    """the alembic CLI in its own process - like the migrate container"""
    return subprocess.Popen([sys.executable, "-m", "alembic", *args], cwd=ROOT, text=True,
                            env={**os.environ, **env}, stderr=subprocess.PIPE)


def finish(p: subprocess.Popen) -> tuple[int, str]:
    _, err = p.communicate(timeout=60)
    return p.returncode, err


def test_one_head(cfg: Config) -> None:
    assert ScriptDirectory.from_config(cfg).get_heads() == ["0005"] == [head_revision()]


def test_down_to_nothing_and_up_again(cfg: Config) -> None:
    command.downgrade(cfg, "base")
    with psycopg.connect(URL) as conn:
        assert conn.execute("SELECT to_regclass('courses')").fetchone()[0] is None
    command.upgrade(cfg, "head")
    assert version() == "0005"


def test_the_tables_match_the_migrations(cfg: Config) -> None:
    command.check(cfg)              # AutogenerateDiffsDetected if app/tables.py has drifted


def test_an_existing_database_is_stamped_not_migrated(cfg: Config) -> None:
    drop_everything()
    with psycopg.connect(URL, autocommit=True) as conn:              # the Video 59 database
        conn.execute(VIDEO_59)
        conn.execute("INSERT INTO courses (title) VALUES ('PostgreSQL in Compose')")
    with pytest.raises(Exception, match="already exists"):         # 0001 = CREATE TABLE courses
        command.upgrade(cfg, "head")
    assert version() is None                       # rolled back: not even alembic_version
    command.stamp(cfg, "0001")                     # "this database is already at 0001"
    command.upgrade(cfg, "head")
    with psycopg.connect(URL) as conn:
        assert conn.execute("SELECT name, level FROM courses").fetchall() == [
            ("PostgreSQL in Compose", "beginner")]


def test_two_migrators_at_the_same_time() -> None:
    drop_everything()
    first, second = alembic("upgrade", "head"), alembic("upgrade", "head")
    results = [finish(p) for p in (first, second)]
    assert [code for code, _ in results] == [0, 0]    # the advisory lock: one after the other
    assert sum("Running upgrade  -> 0001" in err for _, err in results) == 1
    assert version() == "0005"


def test_a_migration_does_not_wait_forever_for_a_lock(cfg: Config) -> None:
    command.downgrade(cfg, "0001")
    with psycopg.connect(URL) as busy:                  # a long transaction reads courses ...
        busy.execute("SELECT count(*) FROM courses")
        t0 = time.perf_counter()
        p = alembic("upgrade", "head", MIGRATION_LOCK_TIMEOUT="1s")
        code, err = finish(p)
        busy.rollback()
    assert code == 1 and "canceling statement due to lock timeout" in err
    assert time.perf_counter() - t0 < 10
    assert version() == "0001"                             # nothing half-done


def test_the_sql_for_a_review(cfg: Config, capsys: pytest.CaptureFixture[str]) -> None:
    command.upgrade(cfg, "0001:head", sql=True)            # offline: prints, runs nothing
    sql = capsys.readouterr().out
    assert "ALTER TABLE courses ADD COLUMN level TEXT DEFAULT 'beginner' NOT NULL;" in sql
    assert "CREATE INDEX CONCURRENTLY ix_courses_created_at ON courses (created_at);" in sql


def test_a_bad_revision_is_an_error(cfg: Config) -> None:
    with pytest.raises(CommandError):
        command.upgrade(cfg, "9999")
